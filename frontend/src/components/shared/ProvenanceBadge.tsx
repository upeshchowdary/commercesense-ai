export function ProvenanceBadge({
  provenance,
  className,
  showTooltip = true,
}: {
  provenance?: ProvenanceKind | null
  className?: string
  showTooltip?: boolean
}) {
  const norm = (provenance || 'MISSING').toUpperCase()
  const cfg = CONFIGS[norm] || CONFIGS['MISSING']
  const Icon = cfg.icon

  return (
    <span
      title={showTooltip ? cfg.tooltip : undefined}
      className={cn(
        'inline-flex items-center gap-1.5 px-2 py-0.5 rounded text-[11px] font-medium border tracking-tight shrink-0 transition-colors',
        cfg.badgeClasses,
        className,
      )}
    >
      <Icon className="size-3 shrink-0" />
      <span>{cfg.label}</span>
    </span>
  )
}

